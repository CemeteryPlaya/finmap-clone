import { runImportCheck } from './lib/import-check-cli';

// Сверка импорта с файлом (§12 спецификации импорта):
//   npm run import:check -- <файл .xlsx или .csv> <id компании> [--today ГГГГ-ММ-ДД]
// id компании — число в адресе журнала: /c/<id>/log. --today — «сегодня» для разбора (строки позже — плановые и не
// считаются, как при импорте); по умолчанию — сегодня в APP_TIMEZONE. Сверяется вся компания, не только этот файл.
// База открывается только на чтение (приложение может работать); файл читается тем же разборщиком, что импорт, и никуда
// не копируется. Выход 0 — «Совпадает», 1 — расхождения, несверенные строки или ошибка. Разбор аргументов и сама сверка —
// в scripts/lib/import-check-cli.ts (там же тесты).

process.exitCode = runImportCheck(process.argv.slice(2), { log: (l) => console.log(l), error: (l) => console.error(l) });
